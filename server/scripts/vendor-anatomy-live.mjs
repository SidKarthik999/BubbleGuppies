// Regenerates server/vendor/anatomy-live-bundle.mjs from ../anatomy-live.
//
//   node server/scripts/vendor-anatomy-live.mjs
//
// Why: on Vercel the "api" service is deployed from server/ only, its code
// can't rely on files outside that folder, and the filesystem is read-only, so
// /api/draw can't run anatomy-live's build at request time. This script runs
// anatomy-live's own build.mjs and stores the resulting self-contained bundle
// as a JS module the API imports statically. Run it after changing anatomy-live
// and commit the result (server/test/draw-vendor.test.mjs checks it is current).

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const anatomyDir = join(here, "..", "..", "anatomy-live");
const outFile = join(here, "..", "vendor", "anatomy-live-bundle.mjs");

export function buildBundleSource() {
  execFileSync(process.execPath, ["build.mjs"], { cwd: anatomyDir, stdio: "ignore", timeout: 60_000 });
  return readFileSync(join(anatomyDir, "dist", "server", "index.js"), "utf8");
}

export function vendorModule(source) {
  return (
    "// GENERATED by server/scripts/vendor-anatomy-live.mjs from ../anatomy-live. Do not edit.\n" +
    "// Anatomy Live's built worker bundle, as a string, so the API needs no\n" +
    "// files outside server/ and no build step at request time.\n" +
    `export default ${JSON.stringify(source)};\n`
  );
}

if (import.meta.url === `file://${process.argv[1]}`) {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, vendorModule(buildBundleSource()));
  console.log(`Wrote ${outFile}`);
}
